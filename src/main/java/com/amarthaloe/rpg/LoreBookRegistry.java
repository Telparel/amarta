    public final int spineColor;
    public final boolean defaultUnlocked;
    public final String[] pages;

    LoreBookRegistry(String id, String spineTitle, String subtitle, int spineColor, boolean defaultUnlocked, String[] pages) {
        this.id = id;
        this.spineTitle = spineTitle;
        this.subtitle = subtitle;
        this.spineColor = spineColor;
        this.defaultUnlocked = defaultUnlocked;
        this.pages = pages;
    }

    public static LoreBookRegistry byId(String id) {
        for (LoreBookRegistry b : values()) {
            if (b.id.equalsIgnoreCase(id)) return b;
        }
        return null;
    }

    // Создает физический предмет лорной книги в инвентарь игрока
    public ItemStack createBookItemStack() {
        ItemStack stack = new ItemStack(Items.ENCHANTED_BOOK);
        stack.set(DataComponents.CUSTOM_NAME, Component.literal("§6§lФолиант: " + this.spineTitle));
        stack.set(DataComponents.LORE, new ItemLore(List.of(
                Component.literal("§7" + this.subtitle),
                Component.literal("§eОткройте [M] -> ИНФОРМАЦИЯ или нажмите ПКМ,"),
                Component.literal("§eчтобы поместить книгу на свою полку знаний!")
        )));
        CompoundTag customTag = new CompoundTag();
        customTag.putString("amarthaloe_lore_book", this.id);
        stack.set(DataComponents.CUSTOM_DATA, CustomData.of(customTag));
        return stack;
    }

    public static LoreBookRegistry fromItemStack(ItemStack stack) {
        if (stack == null || stack.isEmpty()) return null;
        CustomData cd = stack.get(DataComponents.CUSTOM_DATA);
        if (cd == null) return null;
        CompoundTag tag = cd.copyTag();
        if (!tag.contains("amarthaloe_lore_book")) return null;
        return byId(tag.getString("amarthaloe_lore_book"));
    }
